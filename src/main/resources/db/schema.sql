CREATE SCHEMA IF NOT EXISTS public;
CREATE TABLE IF NOT EXISTS customers (
    customer_id VARCHAR(20) PRIMARY KEY,
    customer_tier VARCHAR(20) NOT NULL
);

CREATE TABLE IF NOT EXISTS managers (
    manager_id VARCHAR(20) PRIMARY KEY,
    manager_email VARCHAR(255) NOT NULL,
    manager_status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
    manager_name VARCHAR(100)
);

CREATE TABLE IF NOT EXISTS agents (
    agent_id VARCHAR(20) PRIMARY KEY,
    manager_id VARCHAR(20),
    agent_status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
    FOREIGN KEY (manager_id) REFERENCES managers(manager_id)
);

CREATE TABLE IF NOT EXISTS sla_policies (
    priority VARCHAR(5) NOT NULL,
    customer_tier VARCHAR(20) NOT NULL,
    first_response_target_mins INT NOT NULL,
    resolution_target_mins INT NOT NULL,
    business_calendar_code VARCHAR(30) NOT NULL,
    PRIMARY KEY (priority, customer_tier)
);

CREATE TABLE IF NOT EXISTS tickets (
    ticket_id VARCHAR(30) PRIMARY KEY,
    subject VARCHAR(255) NOT NULL,
    priority VARCHAR(5) NOT NULL,
    ticket_status VARCHAR(25) NOT NULL,
    customer_id VARCHAR(20) NOT NULL,
    assigned_agent_id VARCHAR(20),
    created_at TIMESTAMP NOT NULL,
    first_response_at TIMESTAMP,
    resolved_at TIMESTAMP,
    updated_at TIMESTAMP,
    FOREIGN KEY (customer_id) REFERENCES customers(customer_id),
    FOREIGN KEY (assigned_agent_id) REFERENCES agents(agent_id)
);

CREATE TABLE IF NOT EXISTS ticket_sla_state (
    ticket_id VARCHAR(30) PRIMARY KEY,
    response_elapsed_mins INT DEFAULT 0,
    resolution_elapsed_mins INT DEFAULT 0,
    response_band VARCHAR(20),
    resolution_band VARCHAR(20),
    last_alert_level_response INT DEFAULT 0,
    last_alert_level_resolution INT DEFAULT 0,
    last_alerted_at TIMESTAMP,
    last_evaluated_run_id VARCHAR(40),
    FOREIGN KEY (ticket_id) REFERENCES tickets(ticket_id)
);

CREATE TABLE IF NOT EXISTS ticket_pause_history (
    pause_seq BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticket_id VARCHAR(30) NOT NULL,
    pause_status VARCHAR(25) NOT NULL,
    paused_from TIMESTAMP NOT NULL,
    paused_to TIMESTAMP,
    FOREIGN KEY (ticket_id) REFERENCES tickets(ticket_id)
);

CREATE TABLE IF NOT EXISTS sla_evaluation_runs (
    run_id VARCHAR(40) PRIMARY KEY,
    started_at TIMESTAMP NOT NULL,
    completed_at TIMESTAMP,
    evaluated_count INT DEFAULT 0,
    on_track_count INT DEFAULT 0,
    at_risk_count INT DEFAULT 0,
    breached_count INT DEFAULT 0,
    severe_count INT DEFAULT 0,
    escalated_count INT DEFAULT 0,
    events_published INT DEFAULT 0,
    digests_sent INT DEFAULT 0,
    suppressed_count INT DEFAULT 0,
    run_status VARCHAR(20) NOT NULL,
    correlation_id VARCHAR(50)
);

CREATE TABLE IF NOT EXISTS sla_alert_log (
    alert_seq BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id VARCHAR(40) NOT NULL,
    ticket_id VARCHAR(30) NOT NULL,
    clock_type VARCHAR(15) NOT NULL,
    from_level INT NOT NULL,
    to_level INT NOT NULL,
    band VARCHAR(20) NOT NULL,
    event_published BOOLEAN DEFAULT FALSE,
    email_status VARCHAR(20),
    suppressed_reason VARCHAR(40),
    processing_token VARCHAR(100),
    alerted_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_alert UNIQUE (ticket_id, clock_type, to_level)
);